def test_cece_paths_are_the_run_directorys(wm_set: Path) -> None:
    cece = yaml.safe_load((wm_set / "cece.yaml").read_text())
    streams = {s["name"]: s for s in cece["cece_data"]["streams"]}
    assert len(streams) == 18
    assert len(cece["nuopc"]["export_fields"]) == 33
    # a single-file stream is the inventory under the ExtData link of the run directory
    assert streams["so2_aviation_lto"]["file"] == (
        "ExtData/PIESA/sfc/HTAP/v2.2/htap-v2.2.emis_so2.aviation_lto.x3600_y1800_t12.2010.nc4"
    )
    # a daily series is the window file the run directory stages (until CECE expands date tokens)
    assert streams["anthro1"]["file"] == "streams/CEDS.2019.emis.nc"
    assert streams["fire"]["file"] == "streams/qfed2.emis_so2.006.nc4"
    assert all(not Path(s["file"]).is_absolute() for s in streams.values())
    assert streams["anthro1"]["tintalgo"] == "nearest"
    assert streams["fire"]["tintalgo"] == "linear"
    assert cece["driver"]["start_time"] == "2021-03-22T06:00:00"
    assert gc.validate_cece_file(wm_set / "cece.yaml") == []


def test_the_science_config_is_production_with_extemis_replaced(wm_set: Path) -> None:
    base = yaml.safe_load(BASE_CONFIG.read_text())
    ours = yaml.safe_load((wm_set / "CATChem_new_config.yml").read_text())
    assert list(ours) == list(base)
    for key in base:
        if key != "processes":
            assert ours[key] == base[key], key
    assert list(ours["processes"]) == list(base["processes"])
    for name, block in base["processes"].items():
        if name != "extemis":
            assert ours["processes"][name] == block, name
    # the production file's own names for its two companions, relative to the run directory
    assert ours["simulation"]["species_filename"] == "./CATChem_species.yml"
    assert ours["simulation"]["emission_filename"] == "./CATChem_emission.yml"
    ext = ours["processes"]["extemis"]
    assert ext["activate"] is True
    assert ext["source"] == "nuopc_import"
    assert ext["volcano"] == {"activate": False, "gridded": False}
    assert ext["point"] == {"activate": False, "gridded": False}
    gridded = {
        k: v for k, v in ext.items() if isinstance(v, dict) and v.get("gridded", True)
    }
    assert len(gridded) == 18
    assert all("source_file" not in block for block in gridded.values())


def test_the_emission_map_is_the_production_map(wm_set: Path) -> None:
    production = yaml.safe_load(PRODUCTION_MAP.read_text())
    ours = yaml.safe_load((wm_set / "CATChem_emission.yml").read_text())
    assert "volcano" not in ours
    assert set(ours) == set(production) - {"volcano"}
    for category, variables in ours.items():
        assert set(variables) == set(production[category]), category
        for variable, entry in variables.items():
            theirs = production[category][variable]
            for key in ("long_name", "scale", "map"):
                assert entry[key] == theirs[key], (category, variable, key)


