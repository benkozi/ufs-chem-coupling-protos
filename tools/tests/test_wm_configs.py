def test_absolute_layout_keeps_its_rules(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    manifest = mf.default_manifest(
        resolution="C48", out_dir=Path("data/C48"), command="test"
    )
    path = tmp_path / "data" / "C48" / "manifest.yaml"
    manifest.to_yaml(path)
    with caplog.at_level(logging.ERROR, logger=log.ROOT_NAME):
        assert gc.main(["--manifest", str(path), "--out", str(tmp_path / "o")]) == 2
        assert "--pets" in caplog.text
        base = ["--manifest", str(path), "--out", str(tmp_path / "o"), "--pets", "6"]
        assert gc.main([*base, "--catchem-base-config", str(BASE_CONFIG)]) == 2
        assert "--catchem-base-config needs --layout run-dir" in caplog.text
    for both in (
        [],
        ["--manifest", str(path), "--from-defaults", str(MANIFEST_DEFAULTS)],
    ):
        with pytest.raises(SystemExit):
            gc.main([*both, "--out", str(tmp_path / "o"), "--pets", "6"])


