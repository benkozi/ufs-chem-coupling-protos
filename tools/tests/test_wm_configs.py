def test_the_wm_sequence_is_the_prototypes_without_the_totals_connector() -> None:
    defaults = gd.GenDefaults.from_yaml(GEN_DEFAULTS)
    assert defaults.wm_driver is not None
    assert [c.label for c in defaults.wm_driver.components] == ["ATM", "CHM", "CECE"]
    assert defaults.wm_driver.run_sequence == [
        line for line in defaults.run_sequence if line != "CECE -> ATM"
    ]
    doc = yaml.safe_load(GEN_DEFAULTS.read_text())
    doc["wm_driver"]["run_sequence"].remove("CECE")
    with pytest.raises(pydantic.ValidationError, match=r"wm_driver\.run_sequence"):
        gd.GenDefaults.model_validate(doc)
    doc = yaml.safe_load(GEN_DEFAULTS.read_text())
    doc["wm_driver"]["components"].pop()
    with pytest.raises(pydantic.ValidationError, match="names a component"):
        gd.GenDefaults.model_validate(doc)
    assert gd.GenDefaults.from_yaml(get_settings().gen_defaults_file).wm_driver is None


