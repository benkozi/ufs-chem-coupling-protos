def test_a_manifest_gives_the_same_set_as_its_defaults(
    wm_set: Path, tmp_path: Path
) -> None:
    # the layout make_mock_data writes: paths under the manifest's own directory, relative to the data root
    manifest = mf.default_manifest(
        resolution="C96",
        out_dir=Path("data/C96_realistic"),
        command="test",
        defaults_file=MANIFEST_DEFAULTS,
    )
    path = tmp_path / "data" / "C96_realistic" / "manifest.yaml"
    manifest.to_yaml(path)
    out = tmp_path / "from_manifest"
    args = [
        "--manifest",
        str(path),
        "--data-root",
        str(tmp_path),
        "--defaults",
        str(GEN_DEFAULTS),
    ]
    args += [
        "--layout",
        "run-dir",
        "--catchem-base-config",
        str(BASE_CONFIG),
        "--out",
        str(out),
    ]
    assert gc.main(args) == 0
    for name in SET_NAMES:
        ours = (out / name).read_text().split("\n\n", 1)[1]
        theirs = (wm_set / name).read_text().split("\n\n", 1)[1]
        assert ours == theirs, name


