def without_cece(text: str) -> str:
    """The template with the generator's header, the CECE block and the CECE run-sequence lines taken out."""
    body = text.split("\n\n", 1)[1]
    body = re.sub(r"# CECE #\n(?:.+\n)+\n", "", body)
    body = body.replace(
        "EARTH_component_list: ATM CHM CECE", "EARTH_component_list: ATM CHM"
    )
    return "".join(
        line for line in body.splitlines(keepends=True) if "CECE" not in line
    )


