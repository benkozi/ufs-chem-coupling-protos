def test_no_file_names_a_place_on_this_machine(wm_set: Path, tmp_path: Path) -> None:
    for name in SET_NAMES:
        text = (wm_set / name).read_text()
        assert str(tmp_path) not in text, name
        assert str(REPO_ROOT) not in text, name
        # a value that starts with a slash is an absolute path
        assert not re.search(r"(?m)[:=-]\s+[\"']?/\w", text), name
        assert not re.search(r"20\d\d-\d\d-\d\dT\d\d:\d\d:\d\d\.\d+", text), name


